
import streamlit as st
import pandas as pd
import joblib

# Page configuration
st.set_page_config(
    page_title="Protein Stability Predictor",
    page_icon="🧬",
    layout="centered"
)

# Load the trained pipeline
@st.cache_resource
def load_model():
    return joblib.load("Notebooks\Model\Protein_stability_model.pkl")

model = load_model()

# App title and educational introduction
st.title("🧬 Protein Stability Prediction")
st.write(
    "Predict the change in protein stability (ddG) "
    "using a trained machine learning model."
)


st.subheader("Enter mutation details")

# Input fields
col1, col2 = st.columns(2)

amino_acids = [
    "A", "R", "N", "D", "C",
    "Q", "E", "G", "H", "I",
    "L", "K", "M", "F", "P",
    "S", "T", "W", "Y", "V"
]

with col1:
    wild_type = st.selectbox(
        "Wild-Type Amino Acid",
        amino_acids
    )

    position = st.number_input(
        "Mutation position",
        min_value=1,
        value=25,
        step=1
    )

    conservation = st.number_input(
        "Conservation score",
        min_value=0.0,
        max_value=1.0,
        value=0.85,
        step=0.01
    )

    is_back_to_consensus = st.selectbox(
        "Back-to-consensus mutation?",
        [0, 1],
        format_func=lambda x: "No (0)" if x == 0 else "Yes (1)"
    )

with col2:
    mutation = st.selectbox(
        "Mutant Amino Acid",
        amino_acids
    )

    secondary_structure = st.selectbox(
        "Secondary structure",
        ["H", "E", "C"],
        format_func=lambda x: {
            "H": "H — Helix",
            "E": "E — Sheet",
            "C": "C — Coil"
        }[x]
    )

    is_essential = st.selectbox(
        "Is the position essential?",
        [0, 1],
        format_func=lambda x: "No (0)" if x == 0 else "Yes (1)"
    )

# Predict when the button is clicked
if st.button("Predict ddG", type="primary"):
    if wild_type == mutation:
        st.warning(
            "The wild-type and mutant amino acids are identical. "
            "Check whether this is a valid mutation."
        )
    else:
        sample = pd.DataFrame([{
            "wild_type": wild_type,
            "mutation": mutation,
            "position": position,
            "secondary_structure": secondary_structure,
            "conservation": conservation,
            "is_back_to_consensus": is_back_to_consensus,
            "is_essential": is_essential
        }])

        try:
            prediction = model.predict(sample)[0]

            st.subheader("Prediction result")
            st.metric("Predicted ddG", f"{prediction:.4f}")

            st.write(
                "This value is  generated by the "
                "trained model. Its reliability depends on the "
                "training data and model performance."
            )

            st.caption(
                "Confirm the dataset's ddG definition, sign "
                "convention, and units before interpreting this "
                "value as stabilizing or destabilizing."
            )

            with st.expander("View input features"):
                st.dataframe(sample, use_container_width=True)

        except Exception as error:
            st.error(f"Prediction failed: {error}")
            st.write(
                "Check that the input feature names, categories, "
                "and data types match those used during training."
            )

st.divider()

st.subheader("How does this application work?")
st.markdown("""
1. **Input:** Enter a protein mutation and its features.
2. **Preprocessing:** The saved pipeline encodes categorical
   features and handles missing values.
3. **Prediction:** XGBoost estimates the ddG value.
4. **Interpretation:** Compare predictions with experimental
   measurements and the dataset's ddG convention.
""")
